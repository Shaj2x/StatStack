#!/usr/bin/env python3
"""Rebuild StatStack's SEASONS player database from stats.nba.com via nba_api.

Usage:
    pip install -r scripts/requirements.txt
    python scripts/fetch_nba_data.py                  # every season in SEASONS below
    python scripts/fetch_nba_data.py 2023-24 1986-87  # only these seasons

For each season it pulls regular-season per-game stats, keeps the players who
logged the most minutes (among those who played a meaningful share of games),
assigns card rarity by rank within that season, and writes:
  - data/seasons.json   (cached results, merged across runs)
  - index.html          (the API_SEASONS block between the SEASONS:BEGIN / SEASONS:END
                         markers; the game uses these in place of the hand-entered SEASONS)

stats.nba.com rejects many cloud/datacenter IPs, so run this from a home or
office connection.
"""

import json
import re
import sys
import time
from pathlib import Path

from nba_api.stats.endpoints import leaguedashplayerstats, leagueleaders

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "index.html"
CACHE = ROOT / "data" / "seasons.json"

# Seasons offered in the game, newest first. The first one is labelled "(Current)".
SEASONS = [
    "2025-26", "2024-25", "2023-24", "2022-23", "2021-22", "2019-20",
    "2017-18", "2015-16", "2012-13", "2009-10", "2007-08", "2004-05",
    "2001-02", "1999-00", "1996-97", "1993-94", "1991-92", "1989-90",
    "1986-87", "1984-85",
]

PLAYERS_PER_SEASON = 120
MIN_GP_SHARE = 0.4        # must have played 40% of the season's max games played
RARITY_TIERS = [          # (tier, cumulative share of the ranked pool)
    ("legendary", 0.04),
    ("epic", 0.12),
    ("rare", 0.35),
    ("common", 1.0),
]
REQUEST_DELAY = 1.5       # seconds between requests; stats.nba.com throttles bursts
RETRIES = 3

BEGIN = "// <SEASONS:BEGIN> generated by scripts/fetch_nba_data.py — do not edit by hand"
END = "// <SEASONS:END>"


def fetch_raw(season):
    """Return a list of dicts with PLAYER_ID, PLAYER_NAME, TEAM, GP, MIN, PTS, REB, AST, STL, BLK."""
    for attempt in range(1, RETRIES + 1):
        try:
            df = leaguedashplayerstats.LeagueDashPlayerStats(
                season=season,
                season_type_all_star="Regular Season",
                per_mode_detailed="PerGame",
                timeout=60,
            ).get_data_frames()[0]
            if not df.empty:
                df = df.rename(columns={"TEAM_ABBREVIATION": "TEAM"})
                return df.to_dict("records")
            # Older seasons can come back empty here; the leaders endpoint covers them.
            time.sleep(REQUEST_DELAY)
            df = leagueleaders.LeagueLeaders(
                season=season,
                season_type_all_star="Regular Season",
                per_mode48="PerGame",
                scope="S",
                stat_category_abbreviation="MIN",
                timeout=60,
            ).get_data_frames()[0]
            df = df.rename(columns={"PLAYER": "PLAYER_NAME"})
            return df.to_dict("records")
        except Exception as exc:  # network errors, timeouts, throttling
            if attempt == RETRIES:
                raise
            wait = REQUEST_DELAY * 2 ** attempt
            print(f"  {season}: {exc.__class__.__name__}, retrying in {wait:.0f}s")
            time.sleep(wait)


def build_season(rows):
    """Pick the season's player pool and convert rows to StatStack's player schema."""
    max_gp = max((r["GP"] for r in rows), default=0)
    qualified = [r for r in rows if r["GP"] >= max_gp * MIN_GP_SHARE]
    pool = sorted(qualified, key=lambda r: r["MIN"], reverse=True)[:PLAYERS_PER_SEASON]

    # Rarity follows production (points + rebounds + assists) within the pool.
    by_impact = sorted(pool, key=lambda r: r["PTS"] + r["REB"] + r["AST"], reverse=True)
    rarity = {}
    for i, r in enumerate(by_impact):
        share = (i + 1) / len(by_impact)
        rarity[r["PLAYER_ID"]] = next(tier for tier, cutoff in RARITY_TIERS if share <= cutoff)

    players = [
        {
            "name": r["PLAYER_NAME"],
            "team": r["TEAM"],
            "ppg": round(float(r["PTS"]), 1),
            "rpg": round(float(r["REB"]), 1),
            "apg": round(float(r["AST"]), 1),
            "spg": round(float(r["STL"] or 0), 1),
            "bpg": round(float(r["BLK"] or 0), 1),
            "rarity": rarity[r["PLAYER_ID"]],
            "img": str(r["PLAYER_ID"]),
        }
        for r in by_impact
    ]
    return players


def to_js(data):
    """Render API_SEASONS in the same one-player-per-line style as SEASONS."""
    lines = [BEGIN, "const API_SEASONS = {"]
    for season in (s for s in SEASONS if s in data):
        label = f"{season} (Current)" if season == SEASONS[0] else season
        lines.append(f'"{season}": {{ label:{json.dumps(label)}, players:[')
        for p in data[season]:
            fields = ",".join(f"{k}:{json.dumps(v, ensure_ascii=False)}" for k, v in p.items())
            lines.append(f"  {{{fields}}},")
        lines.append("]},")
    lines += ["};", END]
    return "\n".join(lines)


def write_index(data):
    html = INDEX.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(html):
        sys.exit(f"Could not find SEASONS markers in {INDEX}")
    INDEX.write_text(pattern.sub(lambda _: to_js(data), html, count=1), encoding="utf-8")


def main():
    wanted = sys.argv[1:] or SEASONS
    unknown = [s for s in wanted if s not in SEASONS]
    if unknown:
        sys.exit(f"Unknown season(s): {', '.join(unknown)}. Add them to SEASONS first.")

    data = json.loads(CACHE.read_text(encoding="utf-8")) if CACHE.exists() else {}
    for season in wanted:
        print(f"Fetching {season}…")
        players = build_season(fetch_raw(season))
        if not players:
            print(f"  {season}: no data returned, skipping")
            continue
        data[season] = players
        print(f"  {season}: {len(players)} players, top scorer "
              f"{max(players, key=lambda p: p['ppg'])['name']}")
        CACHE.parent.mkdir(exist_ok=True)
        CACHE.write_text(json.dumps(data, indent=1, ensure_ascii=False), encoding="utf-8")
        time.sleep(REQUEST_DELAY)

    write_index(data)
    print(f"Wrote {len(data)} seasons to {INDEX.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
