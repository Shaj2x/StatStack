// Builds js/ratings.js: the real NBA 2K overall for every card where one
// exists, from the nba2kapi dataset (https://github.com/wkoverfield/nba2kapi,
// scraped from 2kratings.com).
//
//   git clone --depth 1 https://github.com/wkoverfield/nba2kapi ../nba2kapi
//   node scripts/build_ratings.js ../nba2kapi
//   node scripts/build_catalog.js        (so the server uses the same numbers)
//
// Where the ratings come from, best first:
// - data/roster-archive/2K26.json: NBA 2K26 frozen at the end of its cycle
//   (August 2026), so end-of-season ratings for 2025-26
// - nba2k-all-players.json: the live scrape, for anything the archive lacks
// - "Classic" teams (e.g. 1995-96 Chicago Bulls): 2K's ratings for that team's
//   season, used for that season's card
// Every other card gets an estimate fitted to these real ratings (js/app.js).

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const src = process.argv[2];
if (!src) {
  console.error("Usage: node scripts/build_ratings.js <path to nba2kapi clone>");
  process.exit(1);
}

const ctx = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, "js/data.js"), "utf8") + ";this.SEASONS = SEASONS;", ctx);
const SEASONS = ctx.SEASONS;

// Names differ in accents, punctuation and suffixes between the two sources
const norm = s => s.normalize("NFKD").replace(/[̀-ͯ]/g, "").toLowerCase()
  .replace(/[.'’]/g, "").replace(/\b(jr|sr|ii|iii|iv)\b/g, "").replace(/[^a-z ]/g, " ").replace(/\s+/g, " ").trim();

const archive = JSON.parse(fs.readFileSync(path.join(src, "data/roster-archive/2K26.json"), "utf8"));
const live = JSON.parse(fs.readFileSync(path.join(src, "nba2k-all-players.json"), "utf8")).players;

// "name|season" → 2K overall; earlier sources win
const real = new Map();
for (const list of [archive, live]) {
  for (const p of list) {
    let season = null;
    if (p.teamType === "curr") season = "2025-26";
    else if (p.teamType === "class") {
      const m = String(p.team).match(/^(\d{4})-(\d{2})/);
      if (m) season = `${m[1]}-${m[2]}`;
    }
    if (!season || !Number.isInteger(p.overall)) continue;
    const key = `${norm(p.name)}|${season}`;
    if (!real.has(key)) real.set(key, p.overall);
  }
}

const out = {};
let n = 0;
for (const season of Object.keys(SEASONS)) {
  for (const c of SEASONS[season].players) {
    const ovr = real.get(`${norm(c.name)}|${season}`);
    if (ovr) { out[`${c.name}|${season}`] = ovr; n++; }
  }
}

const js = `// Generated by scripts/build_ratings.js — do not edit by hand.
// Real NBA 2K overall ratings ("Name|Season" → OVR) for the cards that have
// one: NBA 2K26's end-of-season ratings for 2025-26, and 2K's Classic team
// ratings for earlier seasons. Source: nba2kapi (github.com/wkoverfield/nba2kapi),
// data from 2kratings.com. Not affiliated with 2K Sports or the NBA.
const REAL_OVR = ${JSON.stringify(out, null, 0).replace(/,"/g, ',\n  "').replace(/^\{/, "{\n  ").replace(/\}$/, "\n}")};
`;
fs.writeFileSync(path.join(root, "js/ratings.js"), js);
console.log(`Wrote js/ratings.js: real 2K ratings for ${n} cards`);
