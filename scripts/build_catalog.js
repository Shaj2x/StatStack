// Builds supabase/catalog.sql: every card in js/data.js, for the server to
// deal packs and grade answers from. Run it after changing js/data.js, then
// run the output in Supabase's SQL Editor.
//
//   node scripts/build_catalog.js
//
// The rules below (franchises, eras, OVR) mirror js/app.js; the game checks
// on load that the server's OVR matches its own.

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const ctx = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, "js/data.js"), "utf8") + ";this.SEASONS = SEASONS;", ctx);
const SEASONS = ctx.SEASONS;

const SEASON_KEYS = Object.keys(SEASONS).sort((a, b) => parseInt(b) - parseInt(a));
const FRANCHISE = {SEA: "OKC", NJN: "BKN", WSB: "WAS", VAN: "MEM", KCK: "SAC", NOH: "NOP", CHH: "CHA"};
const ERAS = [
  {id: "retro", seasons: k => parseInt(k) < 2000},
  {id: "2000s", seasons: k => parseInt(k) >= 2000 && parseInt(k) < 2011},
  {id: "2010s", seasons: k => parseInt(k) >= 2011 && parseInt(k) < 2021},
  {id: "modern", seasons: k => parseInt(k) >= 2021},
];
const PRODUCTION = c => c.ppg + 1.2 * c.rpg + 1.5 * c.apg + 3 * c.spg + 3 * c.bpg;
const OVR_CURVE = [[1, 97], [2, 95], [5, 92], [10, 89], [20, 85], [40, 81], [60, 78], [90, 74], [120, 70]];
const RARITY_BUMP = {legendary: [2, 90], epic: [1, 85], rare: [0, 0], common: [0, 0]};

function seasonOvrs(season) {
  const players = SEASONS[season].players.slice().sort((a, b) => PRODUCTION(b) - PRODUCTION(a));
  const scale = 120 / Math.max(players.length, 1);
  const map = new Map();
  players.forEach((p, i) => {
    const r = (i + 1) * scale;
    let k = OVR_CURVE.findIndex(([rank]) => rank >= r);
    if (k < 1) k = k === 0 ? 1 : OVR_CURVE.length - 1;
    const [r0, o0] = OVR_CURVE[k - 1], [r1, o1] = OVR_CURVE[k];
    map.set(p.name, Math.round(o0 + (o1 - o0) * Math.min(1, Math.max(0, (r - r0) / (r1 - r0)))));
  });
  return map;
}

const q = s => `'${String(s).replace(/'/g, "''")}'`;
const num = v => (Number.isFinite(v) ? String(v) : "0");
const rows = [];
let ord = 0;
for (const season of SEASON_KEYS) {
  const ovrs = seasonOvrs(season);
  for (const c of SEASONS[season].players) {
    const [bump, floor] = RARITY_BUMP[c.rarity] || [0, 0];
    const ovr = Math.min(99, Math.max(floor, (ovrs.get(c.name) || 70) + bump));
    const era = ERAS.find(e => e.seasons(season)).id;
    rows.push(`(${q(`${c.name}|${season}|${c.team}`)},${ord++},${q(c.name)},${q(season)},${q(c.team)},${q(FRANCHISE[c.team] || c.team)},${q(era)},${q(c.rarity)},${num(c.ppg)},${num(c.rpg)},${num(c.apg)},${num(c.spg)},${num(c.bpg)},${ovr})`);
  }
}

const sql = `-- StatStack card catalog. Generated by scripts/build_catalog.js from js/data.js;
-- do not edit by hand. Run it in Supabase (SQL Editor → New query → Run)
-- after supabase/schema.sql, and again whenever js/data.js changes.

create table if not exists public.catalog (
  key text primary key,          -- "Name|Season|TEAM"
  ord int not null,
  name text not null,
  season text not null,
  team text not null,
  franchise text not null,
  era text not null,
  rarity text not null check (rarity in ('common', 'rare', 'epic', 'legendary')),
  ppg float8 not null, rpg float8 not null, apg float8 not null, spg float8 not null, bpg float8 not null,
  ovr int not null
);
create index if not exists catalog_season on public.catalog (season);
alter table public.catalog enable row level security;
drop policy if exists "Anyone reads the catalog" on public.catalog;
create policy "Anyone reads the catalog" on public.catalog for select using (true);
grant select on public.catalog to anon, authenticated;

-- Fresh copy each run. Owned cards keep pointing at their key; cards that
-- leave the data are kept as rows below with ord -1 so nobody loses them.
drop table if exists catalog_new;
create temporary table catalog_new (like public.catalog);
insert into catalog_new (key, ord, name, season, team, franchise, era, rarity, ppg, rpg, apg, spg, bpg, ovr) values
${rows.join(",\n")};

insert into public.catalog select * from catalog_new
on conflict (key) do update set ord = excluded.ord, name = excluded.name, season = excluded.season, team = excluded.team,
  franchise = excluded.franchise, era = excluded.era, rarity = excluded.rarity, ppg = excluded.ppg, rpg = excluded.rpg,
  apg = excluded.apg, spg = excluded.spg, bpg = excluded.bpg, ovr = excluded.ovr;
update public.catalog set ord = -1 where key not in (select key from catalog_new);
drop table catalog_new;
`;
fs.writeFileSync(path.join(root, "supabase/catalog.sql"), sql);
console.log(`Wrote supabase/catalog.sql with ${rows.length} cards`);
